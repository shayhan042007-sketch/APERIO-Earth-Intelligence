export function getFallbackDetectionZones(scenarioId: string): DetectionZone[] {
  const sid = (scenarioId || '').trim();
  if (VERIFIED_SCENARIO_ZONES[sid]) {
    return VERIFIED_SCENARIO_ZONES[sid];
  }
  const lower = sid.toLowerCase();
  if (lower.includes('fire') || lower.includes('uttarakhand')) {
    return VERIFIED_SCENARIO_ZONES['FIRE-UT-00001'] || [];
  }
  if (lower.includes('landslide') || lower.includes('wayanad') || lower.includes('meppadi')) {
    return VERIFIED_SCENARIO_ZONES['wayanad-landslide'] || [];
  }
  if (lower.includes('flood') || lower.includes('tinsukia') || lower.includes('assam')) {
    return VERIFIED_SCENARIO_ZONES['FLD-Tinsukia'] || [];
  }
  if (lower.includes('def') || lower.includes('ghats')) {
    return VERIFIED_SCENARIO_ZONES['DEF-DEF_00007'] || [];
  }
  return VERIFIED_SCENARIO_ZONES['wayanad-landslide'] || [];
}
